import assert from 'node:assert/strict';
const callbacks = new Map();
let id = 0;
globalThis.setTimeout = (fn, delay) => { const key = ++id; callbacks.set(key, { fn, delay }); return key; };
globalThis.clearTimeout = key => callbacks.delete(key);
globalThis.setInterval = (fn, delay) => { const key = ++id; callbacks.set(key, { fn, delay }); return key; };
globalThis.clearInterval = key => callbacks.delete(key);
const events = {};
const app = { innerHTML: '', addEventListener(name, fn) { events[name] = fn; } };
globalThis.document = { querySelector(sel) { return sel === '#app' ? app : null; } };
const data = new Map();
globalThis.localStorage = { getItem: k => data.get(k) ?? null, setItem: (k, v) => data.set(k, v), removeItem: k => data.delete(k) };
globalThis.window = { confirm: () => true };
await import('./main.mjs');
const { send, getState } = window.__xomNho;
send('SET_SHOP_NAME', 'Quán Hẻm Nhỏ');
send('NAVIGATE');
send('NAVIGATE');
send('BUNDLE_DAY1');
send('BUY');
send('START_DAY');
send('CLOSE');
assert.equal(getState().screen, 'DAY_RESULT');
assert.equal([...callbacks.values()].filter(t => t.delay === 12000).length, 1);
events.toggle({ target: { id: 'day-ledger-details', open: true } });
assert.equal([...callbacks.values()].filter(t => t.delay === 12000).length, 0, 'Opening ledger pauses auto advance');
events.toggle({ target: { id: 'day-ledger-details', open: false } });
const timer = [...callbacks.values()].find(t => t.delay === 12000);
assert.ok(timer);
timer.fn();
assert.equal(getState().screen, 'XOM_OI');
assert.equal(getState().currentDay, 2);
console.log('UI timers: result auto advance, detail pause, resume, and next-day preparation PASS');
