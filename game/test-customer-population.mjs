import assert from 'node:assert/strict';
import {fresh,encode,decode} from './day1-core.mjs';
import {identifyRoster} from './customer-population.mjs';
const a=fresh(42), b=fresh(42), other=fresh(99);
assert.deepEqual(a.dayCustomers,b.dayCustomers);
assert.notDeepEqual(a.dayCustomers.map(c=>c.name),other.dayCustomers.map(c=>c.name));
assert.deepEqual(decode(encode(a)).population,a.population);
const child=a.dayCustomers.find(c=>c.personId==='be_ti');
a.facts[child.personId]={successful_orders:3};a.currentDay=8;
const next=identifyRoster(a,[child]);
assert.equal(next[0].name,child.name);
assert.equal(next[0].preferredRecipe,child.preferredRecipe);
assert.equal(next[0].isRegular,true);
assert.equal(next[0].successfulVisits,3);
const branch=identifyRoster(a,Array.from({length:20},(_,i)=>({id:`office_${i}`,personId:`office_${i}`,archetype:'office',recipe:'TRA_TAC'})),'office');
assert.equal(new Set(branch.map(c=>c.personId)).size,20);
assert.equal(new Set(branch.map(c=>c.name)).size,20);
assert.ok(branch.every(c=>c.visualVariantId==='walkin_office'));
const legacy=fresh(1);delete legacy.population;legacy.dayCustomers[0].name='Khách cũ';
const restored=decode(encode(legacy));
assert.equal(restored.dayCustomers[0].name,'Khách cũ');
assert.equal(restored.population.people[legacy.dayCustomers[0].personId].name,'Khách cũ');
assert.deepEqual(identifyRoster(restored,[restored.dayCustomers[0]])[0].name,'Khách cũ');
console.log('Customer population: seeded identities, returning visits, save migration and district uniqueness PASS');
